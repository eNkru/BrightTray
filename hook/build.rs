//! Embeds the hook DLL's identity as a Windows `VERSIONINFO` resource.
//!
//! The version comes from `Cargo.toml` and the build id from `BRIGHTTRAY_BUILD_ID` (CI sets it
//! to the commit), so the shipped DLL names the release that produced it without a sidecar file
//! that can drift. `embed-resource` is already a workspace build-dependency (`app/build.rs` uses
//! it for the icon), and it shells out to `rc.exe` or `windres` depending on the toolchain, so
//! the nested hook build in `app/build.rs` gets the same resource as a standalone build.
//!
//! This is a build script, not injected code: a build that cannot find its own version should
//! fail loudly here rather than produce a DLL with no identity, which is why the reads below
//! expect rather than default.

use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-env-changed=BRIGHTTRAY_BUILD_ID");

    let version = std::env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION");
    let build_id = std::env::var("BRIGHTTRAY_BUILD_ID").unwrap_or_else(|_| "dev".to_string());
    let numbers = four_part(&version);

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let rc = out_dir.join("version.rc");
    std::fs::write(&rc, resource(&numbers, &build_id))
        .unwrap_or_else(|e| panic!("write {}: {e}", rc.display()));
    embed_resource::compile(&rc, embed_resource::NONE);

    // The injected code logs these and a unit test asserts they come from the manifest.
    println!("cargo:rustc-env=BRIGHTTRAY_HOOK_VERSION={version}");
    println!("cargo:rustc-env=BRIGHTTRAY_HOOK_BUILD_ID={build_id}");
}

/// The four numbers a `FILEVERSION` needs; a crate version has three (or fewer).
///
/// `0.1.2` -> `[0, 1, 2, 0]`, `0.1.2-rc1` -> `[0, 1, 2, 0]` (a pre-release suffix is dropped;
/// releases are tagged `vX.Y.Z`), `1` -> `[1, 0, 0, 0]`.
fn four_part(version: &str) -> [u32; 4] {
    let mut numbers = [0u32; 4];
    for (slot, part) in numbers.iter_mut().zip(version.split(['.', '-', '+'])) {
        *slot = part.parse().unwrap_or(0);
    }
    numbers
}

fn resource(numbers: &[u32; 4], build_id: &str) -> String {
    // The resource compiler has no idea what a Rust string is: escape what would end the
    // quoted value. Verified under `windres`; the `rc.exe` path is the one CI exercises.
    let escape = |value: &str| value.replace('\\', "\\\\").replace('"', "\\\"");
    // `FileVersion` and `ProductVersion` are *strings*, and `FileVersionInfo` reports them
    // verbatim, so they carry the same four numbers the fixed field does. That keeps a check
    // on the shipped artefact meaningful: comparing a three-part string against a padded
    // expectation would fail on every valid build.
    let dotted = format!(
        "{}.{}.{}.{}",
        numbers[0], numbers[1], numbers[2], numbers[3]
    );
    let fixed = format!(
        "{},{},{},{}",
        numbers[0], numbers[1], numbers[2], numbers[3]
    );
    format!(
        r#"// Generated by hook/build.rs - do not edit.
#pragma code_page(65001)
1 VERSIONINFO
 FILEVERSION {fixed}
 PRODUCTVERSION {fixed}
 FILEFLAGSMASK 0x3fL
 FILEFLAGS 0x0L
 FILEOS 0x40004L
 FILETYPE 0x2L
 FILESUBTYPE 0x0L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "BrightTray\0"
      VALUE "FileDescription", "BrightTray shell hook\0"
      VALUE "FileVersion", "{dotted}\0"
      VALUE "InternalName", "brighttray_hook\0"
      VALUE "OriginalFilename", "brighttray_hook.dll\0"
      VALUE "ProductName", "BrightTray\0"
      VALUE "ProductVersion", "{dotted}\0"
      VALUE "BuildId", "{build_id}\0"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        build_id = escape(build_id),
    )
}
